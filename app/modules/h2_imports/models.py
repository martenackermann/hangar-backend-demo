"""H2 tables (SPEC §5.3): ``import_jobs`` and ``import_job_errors``.

``import_jobs.id`` is ``GENERATED BY DEFAULT AS IDENTITY`` (not ``ALWAYS``): the upload
endpoint reserves the id first (``nextval``) so the background job and the stored upload
can reference the import job before the row is inserted (both columns are NOT NULL).
"""

from __future__ import annotations

from datetime import datetime
from typing import TYPE_CHECKING, Any

from sqlalchemy import (
    BigInteger,
    Boolean,
    CheckConstraint,
    ForeignKey,
    Identity,
    Index,
    Integer,
    String,
    text,
)
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.core.db import Base, TimestampMixin, str_enum
from app.core.enums import ImportJobStatus, ImportType

if TYPE_CHECKING:
    from app.core.models import BackgroundJob, StoredFile, User

#: Keys of ``import_jobs.post_process`` (API.md ``ImportJobDetail.postProcess``).
POST_PROCESS_KEYS: tuple[str, ...] = (
    "leaseReturnsLinked",
    "hardwareHold",
    "cancelledByItsm",
    "probablyClosed",
    "reopened",
    "contactsCreated",
    "contactsUpdated",
)


def empty_post_process() -> dict[str, Any]:
    return dict.fromkeys(POST_PROCESS_KEYS, 0)


class ImportJob(TimestampMixin, Base):
    __tablename__ = "import_jobs"
    __table_args__ = (
        Index("ix_import_jobs_created_at", text("created_at DESC")),
        Index("ix_import_jobs_type_created_at", "type", text("created_at DESC")),
    )

    id: Mapped[int] = mapped_column(
        Integer, Identity(always=False), primary_key=True, sort_order=-100
    )
    background_job_id: Mapped[int] = mapped_column(ForeignKey("background_jobs.id"))
    type: Mapped[ImportType] = mapped_column(str_enum(ImportType))
    type_detected: Mapped[bool] = mapped_column(Boolean)
    status: Mapped[ImportJobStatus] = mapped_column(str_enum(ImportJobStatus), index=True)
    file_id: Mapped[int] = mapped_column(ForeignKey("stored_files.id"))
    original_filename: Mapped[str] = mapped_column(String(200))
    options: Mapped[dict[str, Any]] = mapped_column(JSONB, default=dict)
    total_rows: Mapped[int | None] = mapped_column(Integer)
    processed_rows: Mapped[int] = mapped_column(Integer, default=0, server_default="0")
    created_count: Mapped[int] = mapped_column(Integer, default=0, server_default="0")
    updated_count: Mapped[int] = mapped_column(Integer, default=0, server_default="0")
    unchanged_count: Mapped[int] = mapped_column(Integer, default=0, server_default="0")
    skipped_count: Mapped[int] = mapped_column(Integer, default=0, server_default="0")
    error_count: Mapped[int] = mapped_column(Integer, default=0, server_default="0")
    warning_count: Mapped[int] = mapped_column(Integer, default=0, server_default="0")
    post_process: Mapped[dict[str, Any]] = mapped_column(JSONB, default=empty_post_process)
    #: File-level warnings (e.g. ``extra_columns``) — API ``jobLevelWarnings``.
    job_warnings: Mapped[list[Any]] = mapped_column(
        JSONB, default=list, server_default=text("'[]'::jsonb")
    )
    cancel_requested: Mapped[bool] = mapped_column(Boolean, default=False, server_default="false")
    error_report_file_id: Mapped[int | None] = mapped_column(ForeignKey("stored_files.id"))
    #: Unrecoverable failure reason (status ``failed``).
    failure: Mapped[str | None] = mapped_column(String(500))
    created_by: Mapped[int] = mapped_column(ForeignKey("users.id"))
    started_at: Mapped[datetime | None]
    finished_at: Mapped[datetime | None]

    creator: Mapped[User] = relationship(lazy="selectin", foreign_keys=[created_by])
    background_job: Mapped[BackgroundJob] = relationship(lazy="selectin")
    file: Mapped[StoredFile] = relationship(lazy="selectin", foreign_keys=[file_id])
    error_report_file: Mapped[StoredFile | None] = relationship(
        lazy="selectin", foreign_keys=[error_report_file_id]
    )

    @property
    def dry_run(self) -> bool:
        return bool((self.options or {}).get("dryRun"))


class ImportJobError(TimestampMixin, Base):
    """One issue (error or warning) of one row (SPEC §5.3)."""

    __tablename__ = "import_job_errors"
    __table_args__ = (
        Index("ix_import_job_errors_import_job_id_row", "import_job_id", "row_number"),
        CheckConstraint(
            "severity IN ('error', 'warning')", name="ck_import_job_errors_severity_values"
        ),
    )

    id: Mapped[int] = mapped_column(
        BigInteger, Identity(always=True), primary_key=True, sort_order=-100
    )
    import_job_id: Mapped[int] = mapped_column(ForeignKey("import_jobs.id", ondelete="CASCADE"))
    row_number: Mapped[int] = mapped_column(Integer)
    severity: Mapped[str] = mapped_column(String(8))
    column_name: Mapped[str | None] = mapped_column(String(64))
    code: Mapped[str] = mapped_column(String(48))
    message: Mapped[str] = mapped_column(String(500))
    raw_value: Mapped[str | None] = mapped_column(String(500))
    business_key: Mapped[str | None] = mapped_column(String(40))
